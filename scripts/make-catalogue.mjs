// Generates docs/PLAYGROUND-CATALOGUE.md: every playground (shipped + Draft),
// what it does / physics / visuals (from spec hook+one_paragraph+description,
// with fallbacks), and the flags to address (from REVIEW.md + DEVNOTES + .verified).
// Reproducible single source; re-run after sweep progress.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const PG = path.join(ROOT, 'playgrounds');
const DELIM = new RegExp('^-{3}\\n([\\s\\S]*?)\\n-{3}');

function frontmatter(specPath) {
  const fm = {};
  if (!fs.existsSync(specPath)) return fm;
  const txt = fs.readFileSync(specPath, 'utf-8');
  const m = txt.match(DELIM);
  if (!m) return fm;
  for (const line of m[1].split('\n')) {
    const mm = line.match(/^([a-z_]+):\s*(.*)$/);
    if (!mm) continue;
    let v = mm[2].trim();
    if ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"'))) v = v.slice(1, -1);
    fm[mm[1]] = v;
  }
  const body = txt.slice(m[0].length).replace(/^#.*$/m, '').trim();
  fm._firstPara = (body.split('\n\n').find(p => p.trim() && !p.startsWith('#')) || '').replace(/\s+/g, ' ').trim();
  return fm;
}

function reviewFlags(dir) {
  const rp = path.join(dir, 'REVIEW.md');
  if (!fs.existsSync(rp)) return { verdict: '(not yet reviewed)', defects: [] };
  const t = fs.readFileSync(rp, 'utf-8');
  const deep = /deep audit; supersedes/.test(t);
  let verdict = '';
  const v2 = t.match(/##\s*Verdict\s*\n+([^\n#]+)/);
  const vm = t.match(/##\s*A\.[^\n]*\n+([^\n#]+)/);
  verdict = (v2 ? v2[1] : (vm ? vm[1] : '')).trim();
  const defs = [];
  const dm = t.match(/##\s*(?:Defects[^\n]*|C\. Presentability|Action checklist[^\n]*)\n([\s\S]*?)(?:\n##|$)/);
  if (dm) for (const l of dm[1].split('\n')) { const s = l.trim(); if (/^(\d+\.|-|\*)\s/.test(s)) defs.push(s.replace(/^(\d+\.|-|\*)\s*/, '').slice(0, 200)); }
  return { verdict: (deep ? '[deep] ' : '[first-pass] ') + (verdict || '(see REVIEW.md)'), defects: defs.slice(0, 4) };
}

const rows = [];
for (const year of fs.readdirSync(PG).sort()) {
  const yd = path.join(PG, year);
  if (!fs.statSync(yd).isDirectory()) continue;
  for (const slug of fs.readdirSync(yd).sort()) {
    const dir = path.join(yd, slug);
    if (!fs.statSync(dir).isDirectory() || !fs.existsSync(path.join(dir, 'spec.md'))) continue;
    const fm = frontmatter(path.join(dir, 'spec.md'));
    const shipped = fs.existsSync(path.join(dir, '.verified'));
    const swept = fs.existsSync(path.join(dir, 'DEVNOTES.md'));
    const ph = (s) => !s || /STATUS: needs_/.test(s);
    const what = !ph(fm.one_paragraph) ? fm.one_paragraph
      : !ph(fm.description) ? fm.description
      : !ph(fm.hook) ? fm.hook
      : (fm._firstPara || '(no description; placeholder spec)');
    const hook = ph(fm.hook) ? '(placeholder hook, flagged)' : fm.hook;
    const rv = reviewFlags(dir);
    rows.push({ year, slug, title: fm.title || slug, uc: fm.primary_uc || '', tier: fm.tier || '',
      hero: fm.hero_candidate === 'true', shipped, swept, hook, what, verdict: rv.verdict, defects: rv.defects });
  }
}

const shippedN = rows.filter(r => r.shipped).length;
const draftN = rows.length - shippedN;
const sweptN = rows.filter(r => r.swept).length;
const heroN = rows.filter(r => r.hero).length;
let out = `# Playground Catalogue\n\n`;
out += `Generated by scripts/make-catalogue.mjs. Total ${rows.length} playgrounds: `;
out += `${shippedN} shipped (folder has a .verified marker with a verified-at line), `;
out += `${draftN} Draft (no .verified, so build-index.mjs gates them out of the gallery), `;
out += `${sweptN} post-build-swept (have DEVNOTES.md), ${heroN} flagged hero_candidate.\n\n`;
out += `Shipped vs Draft is exactly how scripts/build-index.mjs (line 152) splits the gallery. Flags come from each folder's pre-computed REVIEW.md and DEVNOTES.md.\n\n`;
let cy = '';
for (const r of rows) {
  if (r.year !== cy) { cy = r.year; out += `\n## ${cy}\n\n`; }
  out += `### ${r.title}\n`;
  out += `\`playgrounds/${r.year}/${r.slug}\` | ${r.uc} | ${r.shipped ? 'SHIPPED' : 'DRAFT'}`;
  out += `${r.swept ? ' | swept' : ''}${r.hero ? ' | HERO-CANDIDATE' : ''}${r.tier ? ' | tier:' + r.tier : ''}\n\n`;
  out += `- What it does / physics / visuals: ${r.what}\n`;
  out += `- Hook: ${r.hook}\n`;
  out += `- Review verdict: ${r.verdict}\n`;
  if (r.defects.length) out += `- Flags to address:\n${r.defects.map(d => `  - ${d}`).join('\n')}\n`;
  out += `\n`;
}
fs.writeFileSync(path.join(ROOT, 'docs', 'PLAYGROUND-CATALOGUE.md'), out);
console.log(`Wrote docs/PLAYGROUND-CATALOGUE.md: ${rows.length} playgrounds (${shippedN} shipped, ${draftN} draft, ${sweptN} swept, ${heroN} hero-candidates).`);
